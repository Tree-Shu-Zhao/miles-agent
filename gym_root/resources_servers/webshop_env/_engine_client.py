"""Async HTTP client for the py3.10 WebShop engine server.

The engine speaks the minimal session protocol:

    POST {base}/reset  {"session_id", "task_id", "split", "goal_id"?}  -> {"obs", "info"}
    POST {base}/step   {"session_id", "action"}                        -> {"obs", "reward", "done", "info"}
    POST {base}/close  {"session_id"}                                  -> {}

``goal_id`` is the goal's 16-hex CONTENT id (agent_utils/webshop_goals.py); the
engine resolves it to its list index and answers 400 for an id it does not
have (dataset and engine disagree on catalog / goal code). ``task_id`` is the
legacy positional reference (engine list index). ``goal_id`` is only put on the
wire when given, so the legacy body stays byte-identical.

Deliberately NOT nemo_gym.server_utils.request (which retries connection
errors forever — fine in-mesh, fatal for a wedged engine). Bounded retries,
hard per-call timeout, and — crucially — /step retries ONLY pre-send
(connect) failures: a WebShop click mutates engine session state, so a blind
retry could apply an action twice. Raises EngineError on failure so the
adapter drops the trajectory instead of faking a reward.

Retry matrix (``retries`` attempts after the first; back-off 2s, 4s, ... 10s):

    4xx            never retried (protocol bug, or 410 = episode gone)
    /reset         retried on 5xx and any transport failure, with a FRESH
                   session_id per attempt (a late-landing earlier attempt can
                   then only create an orphan the engine TTL-evicts, never
                   overwrite the live episode)
    /step, /close  retried only on ConnectError / ConnectTimeout (the request
                   provably never reached the engine)

Malformed 2xx bodies (non-JSON, non-object, missing or mistyped fields) are
EngineError too: a protocol fault must surface as an infrastructure failure
(adapter 502 -> run_transport_failed -> group dropped), never as reward 0.
"""

import asyncio
import logging
import uuid
from collections.abc import Callable
from typing import Any

import httpx

logger = logging.getLogger("webshop_env.engine_client")

_MISSING = object()


class EngineError(RuntimeError):
    """An engine call failed.

    ``status`` is the HTTP status of a definitive non-2xx reply (e.g. 410 =
    the engine already dropped this episode, 400 = unknown goal_id / bad goal
    index) and None for transport failures and malformed 2xx bodies — i.e.
    whenever the engine's verdict on the session is unknown.
    """

    def __init__(self, msg: str, status: int | None = None):
        super().__init__(msg)
        self.status = status


class EngineSession:
    """One engine session == one WebShop episode. One client per base_url is
    shared process-wide (keep-alive disabled: a model turn can outlast the
    engine's keep-alive and a reused socket then surfaces as an ambiguous
    ReadError on the non-idempotent /step).

    ``session_id`` is (re)generated by ``reset()`` on every attempt; before the
    first reset it is only a placeholder."""

    _clients: dict[str, httpx.AsyncClient] = {}

    def __init__(self, base_url: str, step_timeout: float, retries: int = 2):
        if not base_url:
            raise EngineError("engine base_url is not configured")
        self.base_url = base_url.rstrip("/")
        self.step_timeout = step_timeout
        self.retries = retries
        self.session_id = uuid.uuid4().hex
        self._closed = False

    @property
    def closed(self) -> bool:
        """True once close() or forget() ran; close() is then a no-op."""
        return self._closed

    @classmethod
    def _client(cls, base_url: str, timeout: float) -> httpx.AsyncClient:
        client = cls._clients.get(base_url)
        if client is None or client.is_closed:
            client = httpx.AsyncClient(
                base_url=base_url,
                timeout=httpx.Timeout(timeout, connect=min(30.0, timeout)),
                limits=httpx.Limits(max_connections=512, max_keepalive_connections=0, keepalive_expiry=0.0),
            )
            cls._clients[base_url] = client
        return client

    async def _post(
        self,
        path: str,
        payload: dict | Callable[[], dict],
        *,
        retries: int | None = None,
        presend_only: bool = False,
    ) -> dict:
        """POST ``payload`` (a dict, or a callable producing the dict — evaluated
        once per attempt) and return the decoded JSON object."""
        retries = self.retries if retries is None else retries
        last_exc: httpx.HTTPError | None = None
        for attempt in range(retries + 1):
            body = payload() if callable(payload) else payload
            try:
                resp = await self._client(self.base_url, self.step_timeout).post(path, json=body)
                resp.raise_for_status()
            except httpx.HTTPError as e:
                last_exc = e
                if isinstance(e, httpx.HTTPStatusError) and e.response.status_code < 500:
                    break  # 4xx = protocol bug / dead session: retrying cannot help
                if presend_only and not isinstance(e, (httpx.ConnectError, httpx.ConnectTimeout)):
                    break  # the request may have reached the engine — no blind /step retry
                if attempt < retries:
                    delay = min(2.0 * (attempt + 1), 10.0)
                    logger.warning(
                        "engine %s%s attempt %d/%d failed (%r); retrying in %.0fs",
                        self.base_url,
                        path,
                        attempt + 1,
                        retries + 1,
                        e,
                        delay,
                    )
                    await asyncio.sleep(delay)
                continue
            return self._decode(path, resp)
        status = getattr(getattr(last_exc, "response", None), "status_code", None)
        raise EngineError(
            f"engine {self.base_url}{path} failed (status={status}): {self._failure_detail(last_exc)}", status=status
        ) from last_exc

    @staticmethod
    def _failure_detail(exc: httpx.HTTPError | None) -> str:
        """The engine's own words for a definitive non-2xx reply — its JSON
        ``detail`` (e.g. WHICH goal_id it does not have and the goals_digest it
        serves), so the adapter's error and the job log say what went wrong
        rather than just "400 Bad Request". Transport failures have no reply:
        the exception repr is all there is."""
        resp = getattr(exc, "response", None)
        if resp is None:
            return repr(exc)
        try:
            body = resp.json()
        except ValueError:
            body = None
        detail = body.get("detail") if isinstance(body, dict) else None
        if detail:
            return str(detail)
        return resp.text[:200] or repr(exc)

    def _decode(self, path: str, resp: httpx.Response) -> dict:
        try:
            data = resp.json()
        except ValueError as e:  # json.JSONDecodeError / UnicodeDecodeError
            raise EngineError(
                f"engine {self.base_url}{path} returned a non-JSON body (status={resp.status_code}): "
                f"{resp.text[:200]!r}"
            ) from e
        if not isinstance(data, dict):
            raise EngineError(
                f"engine {self.base_url}{path} returned a JSON {type(data).__name__}, expected an object"
            )
        return data

    def _field(self, path: str, data: dict, key: str, kinds: type | tuple[type, ...], default: Any = _MISSING) -> Any:
        value = data.get(key, default)
        if value is _MISSING:
            raise EngineError(f"engine {self.base_url}{path} response missing {key!r}: {str(data)[:200]}")
        if not isinstance(value, kinds):
            raise EngineError(
                f"engine {self.base_url}{path} response field {key!r} is {type(value).__name__}: {str(data)[:200]}"
            )
        return value

    async def reset(self, task_id: Any = None, split: str = "train", goal_id: str | None = None) -> tuple[str, dict]:
        def payload() -> dict:
            # F02: a fresh id per attempt. If attempt N timed out but lands on
            # the engine after attempt N+1 succeeded, it creates an orphan
            # session (TTL-evicted) instead of re-resetting the live one.
            self.session_id = uuid.uuid4().hex
            body = {"session_id": self.session_id, "task_id": task_id, "split": split}
            # Omitted rather than sent as null when absent: the legacy body
            # must not change shape for callers that never learned goal_id.
            if goal_id is not None:
                body["goal_id"] = goal_id
            return body

        data = await self._post("/reset", payload)
        obs = self._field("/reset", data, "obs", str)
        info = self._field("/reset", data, "info", dict, default={})
        return obs, info

    async def step(self, action: str) -> tuple[str, float, bool, dict]:
        data = await self._post("/step", {"session_id": self.session_id, "action": action}, presend_only=True)
        obs = self._field("/step", data, "obs", str)
        reward = float(self._field("/step", data, "reward", (int, float)))
        done = self._field("/step", data, "done", bool)
        info = self._field("/step", data, "info", dict, default={})
        return obs, reward, done, info

    def forget(self) -> None:
        """Mark the session closed WITHOUT an HTTP round trip.

        For episodes the engine has already dropped on its side — a terminal
        (done) step, or a 410 on /step — so the adapter's release path does
        not spend a redundant /close call (F33)."""
        self._closed = True

    async def close(self) -> None:
        if self._closed:
            return
        self._closed = True
        try:
            await self._post("/close", {"session_id": self.session_id}, retries=1, presend_only=True)
        except EngineError as e:
            logger.info(
                "engine session %s close failed (status=%s; engine TTL-evicts): %s", self.session_id, e.status, e
            )
